-- | 命題を LaTeX 数式として表示するための文字列。
tikzPropLabel :: Prop -> String
tikzPropLabel PG2          = "$G_2$"
tikzPropLabel PWFG2        = "$\\mathrm{WFG}_2$"
tikzPropLabel PFG2         = "$\\mathrm{FG}_2$"
tikzPropLabel PHasDiamFP   = "$\\exists\\boxtimes\\text{-FP}$"
tikzPropLabel PHasBoxFP    = "$\\exists\\Box\\text{-FP}$"
tikzPropLabel PLoeb        = "$\\mathrm{Loeb}$"
tikzPropLabel PFLoeb       = "$\\mathrm{FLoeb}$"
tikzPropLabel PConsistency = "$\\mathsf{Con}$"

-- | 文脈を LaTeX 数式として表示するための文字列。
tikzContextLabel :: Context -> String
tikzContextLabel COverPreAPS        = "$\\mathsf{PreAPS}$"
tikzContextLabel COverAPS           = "$\\mathsf{APS}$"
tikzContextLabel COverFixedPointAPS = "$\\mathsf{APS}+\\exists\\boxtimes\\text{-FP}$"
tikzContextLabel COverLoebAPS       = "$\\mathsf{LoebAPS}$"
tikzContextLabel COverImpAPS        = "$\\mathsf{ImpAPS}$"
tikzContextLabel COverFin           = "$\\mathsf{fin}$"
tikzContextLabel (CCustom s)        = "$" ++ tikzifyAxioms s ++ "$"

-- | @A1@, @A2@ などの公理名を添字付きに変換: @A1+A2@ → @A_1+A_2@。
tikzifyAxioms :: String -> String
tikzifyAxioms []                = []
tikzifyAxioms ('A':c:rest) | c `elem` ("0123456789" :: String) =
  'A' : '_' : c : tikzifyAxioms rest
tikzifyAxioms (c:rest) = c : tikzifyAxioms rest

-- | 動物園を LaTeX (TikZ) 形式に変換する。
--
-- 出力は @standalone@ クラスの完全な .tex ファイル。@pdflatex@（または
-- @lualatex@／@xelatex@）でコンパイルできる。命題はノードとして縦一列に配置し、
-- 含意は太線・反例は @\\times@ 入りの点線・未解決は @?@ 入りの点線で描画する。
renderTikZ :: [Edge] -> String
renderTikZ es = unlines $
  [ "% Auto-generated by g2-zoo"
  , "% Compile: pdflatex (or lualatex / xelatex) this-file.tex"
  , "\\documentclass[border=15pt]{standalone}"
  , "\\usepackage[utf8]{inputenc}"
  , "\\usepackage[T1]{fontenc}"
  , "\\usepackage{lmodern}"
  , "\\usepackage{amssymb}"
  , "\\usepackage{tikz}"
  , "\\usetikzlibrary{positioning, arrows.meta, decorations.markings, calc}"
  , "\\begin{document}"
  , "\\begin{tikzpicture}["
  , "  every node/.style={font=\\large, inner sep=2pt},"
  , "  proved/.style={->, thick, >={Stealth[length=2.5mm]}},"
  , "  separated/.style={->, dotted, thick, >={Stealth[length=2.5mm]},"
  , "    postaction={decorate, decoration={markings,"
  , "      mark=at position 0.5 with {\\node[fill=white, inner sep=1pt]{$\\times$};}}}},"
  , "  open/.style={->, dotted, thick, >={Stealth[length=2.5mm]},"
  , "    postaction={decorate, decoration={markings,"
  , "      mark=at position 0.5 with {\\node[fill=white, inner sep=1pt]{$?$};}}}}"
  , "]"
  , "% nodes"
  ]
  ++ map renderTikZNode usedProps
  ++
  [ "% edges"
  ]
  ++ map renderTikZEdge es
  ++
  [ "\\end{tikzpicture}"
  , "\\end{document}"
  ]
  where
    usedProps = nub $ concatMap (\e -> [edgeFrom e, edgeTo e]) es

-- | propRank / propColumn に基づく 2D 格子座標にノードを配置する。
-- x 軸: propColumn × 3.5 cm  (列間隔)
-- y 軸: propRank × (−2.5) cm (行間隔、下に行くほど弱い)
renderTikZNode :: Prop -> String
renderTikZNode p =
  "\\node (" ++ propId p ++ ") at (" ++ x ++ "," ++ y ++ ") {"
  ++ tikzPropLabel p ++ "};"
  where
    x = show (fromIntegral (propColumn p) * (3.5 :: Double))
    y = show (fromIntegral (propRank   p) * (-2.5 :: Double))

-- | 辺を描画する。ランク・列の位置から bend 方向を決める。
renderTikZEdge :: Edge -> String
renderTikZEdge e =
  "\\draw[" ++ style ++ "] (" ++ propId (edgeFrom e) ++ ") "
  ++ "to[" ++ bend ++ "] node[midway, sloped, above, fill=white, inner sep=1pt] {"
  ++ tikzContextLabel (edgeCtx e) ++ "} (" ++ propId (edgeTo e) ++ ");"
  where
    fromRank = propRank   (edgeFrom e)
    toRank   = propRank   (edgeTo   e)
    fromCol  = propColumn (edgeFrom e)
    toCol    = propColumn (edgeTo   e)
    -- 縦方向: 下向き(fromRank < toRank)は右曲がり, 上向きは左曲がり
    -- 横方向: 右向き(fromCol < toCol)は右曲がり, 左向きは左曲がり
    bend | fromRank < toRank  = "bend right=20"
         | fromRank > toRank  = "bend left=20"
         | fromCol  < toCol   = "bend right=15"
         | otherwise          = "bend left=15"
    style = case edgeKind e of
      Proved    -> "proved"
      Separated -> "separated"
      Open      -> "open"

