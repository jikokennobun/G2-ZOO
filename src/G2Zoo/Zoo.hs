-- | 出典・補足を Markdown 文字列として書き出す。
-- 画像から外した注釈はここに集約する。
renderNotes :: [Edge] -> String
renderNotes es = unlines $
  [ "# G2 Zoo の辺の出典・注釈"
  , ""
  , "本ファイルは `g2-zoo` が動物園を出力する際に同時に生成する。"
  , "画像に載せない出典・補足を辺ごとに列挙する。"
  , ""
  , "| 種別 | from | 文脈 | to | 注釈 |"
  , "|------|------|------|----|------|"
  ]
  ++ map row es
  where
    row e = "| " ++ kind e ++ " | " ++ propLabel (edgeFrom e)
         ++ " | " ++ contextLabel (edgeCtx e)
         ++ " | " ++ propLabel (edgeTo e)
         ++ " | " ++ (if null (edgeNote e) then "—" else edgeNote e)
         ++ " |"
    kind e = case edgeKind e of
      Proved    -> "成立"
      Separated -> "反例あり"
      Open      -> "未解決"
